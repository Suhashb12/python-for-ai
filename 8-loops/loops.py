"""
What are loops?
Loops let you repeat code without writing it multiple times. Instead of copying and pasting, you tell Python to repeat the code for you.
Without loops:
"""
print("Hello!")
print("Hello!")
print("Hello!")
print("Hello!")
print("Hello!")

# With loops:
for i in range(5):
    print("Hello!")

""" Both do the same thing, but the loop is much cleaner!"""